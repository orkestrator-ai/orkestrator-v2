/**
 * The executable-document Content Security Policy, generated only by
 * application code, plus the script serialization rules its hashes depend on.
 *
 * Hashes authorize exact script bytes; they do not certify intent. The policy
 * never contains `unsafe-eval`, `wasm-unsafe-eval`, a network source or the
 * application origin. `sandbox allow-scripts` only works as an HTTP header, so
 * every consumer (content server, preview worker) sends this as a header.
 */
import { createHash } from "node:crypto";

export const INTERACTIVE_CSP_VERSION = "html-interactive-csp:v1";

/** Origins that may frame an executable document; used only for `frame-ancestors`. */
/**
 * The desktop app's trusted viewer shell is served on this custom standard
 * scheme (see apps/desktop); it is the only non-http(s) ancestor accepted.
 */
export const DESKTOP_ARTIFACT_SHELL_ORIGIN = "orkestrator-artifact-shell://viewer";

export function normalizeFrameAncestors(values: readonly string[]): string[] {
  const result: string[] = [];
  for (const raw of values) {
    const value = raw.trim();
    if (!value) continue;
    if (value.toLowerCase() === DESKTOP_ARTIFACT_SHELL_ORIGIN) {
      if (!result.includes(DESKTOP_ARTIFACT_SHELL_ORIGIN))
        result.push(DESKTOP_ARTIFACT_SHELL_ORIGIN);
      continue;
    }
    // Scheme + host (+ optional port or `:*` for loopback development).
    const match = /^(https?):\/\/([a-z0-9.-]+|\[[0-9a-f:]+\])(?::(\d{1,5}|\*))?$/i.exec(value);
    if (!match) throw new Error(`Invalid frame ancestor: ${value.slice(0, 80)}`);
    const host = match[2]!.toLowerCase();
    if (match[3] === "*" && !["127.0.0.1", "localhost", "[::1]"].includes(host)) {
      throw new Error("Port wildcards are only allowed for loopback frame ancestors");
    }
    if (host.includes("*")) throw new Error("Host wildcards are not allowed in frame ancestors");
    if (!result.includes(value.toLowerCase())) result.push(value.toLowerCase());
  }
  return result;
}

export function inlineScriptHash(text: string): string {
  return `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;
}

export function buildInteractiveCsp(
  scriptHashes: readonly string[],
  frameAncestors: readonly string[],
): string {
  const hashes = Array.from(new Set(scriptHashes)).sort();
  for (const hash of hashes) {
    if (!/^'sha256-[A-Za-z0-9+/]{43}='$/.test(hash)) throw new Error("Invalid script hash");
  }
  const ancestors = frameAncestors.length
    ? normalizeFrameAncestors(frameAncestors).join(" ")
    : "'none'";
  return [
    "default-src 'none'",
    `script-src ${hashes.length ? hashes.join(" ") : "'none'"}`,
    "script-src-attr 'none'",
    "style-src 'unsafe-inline'",
    "img-src data: blob:",
    "font-src data:",
    "media-src 'none'",
    "connect-src 'none'",
    "worker-src 'none'",
    "frame-src 'none'",
    "child-src 'none'",
    "object-src 'none'",
    "manifest-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "sandbox allow-scripts",
    `frame-ancestors ${ancestors}`,
  ].join("; ");
}

/**
 * Checks that a header value is one this module generated (modulo the
 * frame-ancestors list) before anything serves it, then re-applies the
 * currently configured ancestors.
 */
export function rebindFrameAncestors(csp: string, frameAncestors: readonly string[]): string {
  const directives = csp.split(";").map((part) => part.trim());
  const scriptSrc = directives.find((part) => part.startsWith("script-src "));
  if (!scriptSrc) throw new Error("Policy has no script-src");
  const hashes = scriptSrc
    .slice("script-src ".length)
    .split(/\s+/)
    .filter((token) => token !== "'none'");
  const rebuilt = buildInteractiveCsp(hashes, frameAncestors);
  const withoutAncestors = (value: string) =>
    value
      .split(";")
      .map((part) => part.trim())
      .filter((part) => !part.startsWith("frame-ancestors"))
      .join("; ");
  if (withoutAncestors(rebuilt) !== withoutAncestors(csp))
    throw new Error("Policy was not generated by this backend");
  return rebuilt;
}

/**
 * Serialize trusted script text for an inline `<script>` element so the HTML
 * tokenizer ends the element exactly at our closing tag. `</script` and `<!--`
 * (which can enter the "script data escaped" states) are escaped with a
 * backslash, which is an identity escape inside JS strings, templates and
 * regular expressions. The result is round-trip checked by the preparer.
 */
export function escapeInlineScript(text: string): string {
  return text.replace(/<\/(script)/gi, "<\\/$1").replace(/<!--/g, "<\\!--");
}

/** Deterministic, non-secret readiness nonce for one artifact revision. */
export function readinessNonce(artifactId: string, revision: number): string {
  return createHash("sha256")
    .update(`artifact-readiness:v1\u0000${artifactId}\u0000${revision}`)
    .digest("base64url")
    .slice(0, 32);
}
