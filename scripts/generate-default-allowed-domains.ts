#!/usr/bin/env bun
/**
 * Regenerates the image's firewall fallback allowlist from the canonical list
 * in `packages/protocol/src/network-allowlist.ts`.
 *
 *   bun scripts/generate-default-allowed-domains.ts           # write
 *   bun scripts/generate-default-allowed-domains.ts --check   # verify, no writes
 *
 * `docker/init-firewall.sh` and `docker/update-firewall.sh` read the file only
 * when a container's `ALLOWED_DOMAINS` is empty or absent. The backend sends
 * current images `none` for an empty list, so in practice it covers containers
 * started outside Orkestrator.
 * `tests/unit/version-drift.test.ts` fails when the committed file differs.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { imageDefaultAllowedDomains } from "../packages/protocol/src/network-allowlist";

export const DEFAULT_ALLOWED_DOMAINS_FILE = "docker/default-allowed-domains";

export function renderDefaultAllowedDomains(): string {
  return [
    "# Generated by scripts/generate-default-allowed-domains.ts from",
    "# packages/protocol/src/network-allowlist.ts. Do not edit.",
    "# The firewall's fallback when a container has no ALLOWED_DOMAINS.",
    ...imageDefaultAllowedDomains(),
    "",
  ].join("\n");
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error("usage: bun scripts/generate-default-allowed-domains.ts [--check]");
  }
  const path = join(import.meta.dir, "..", DEFAULT_ALLOWED_DOMAINS_FILE);
  const expected = renderDefaultAllowedDomains();
  if (args[0] === "--check") {
    if (readFileSync(path, "utf8") !== expected) {
      console.error(
        `${DEFAULT_ALLOWED_DOMAINS_FILE} is stale; run bun scripts/generate-default-allowed-domains.ts`,
      );
      process.exit(1);
    }
  } else {
    writeFileSync(path, expected);
  }
}
