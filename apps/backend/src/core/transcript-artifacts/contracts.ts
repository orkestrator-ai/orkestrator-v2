/**
 * Internal contracts between the transcript-artifact service (ownership,
 * records, receipts, publication) and the preview infrastructure
 * (preparation, supervised Chromium jobs, executable content serving).
 *
 * The service never runs a browser and the preview runner never touches
 * artifact records: the runner receives exact bytes and returns bounded
 * evidence; the service decides what that evidence proves.
 */
import type {
  ArtifactDiagnostic,
  ArtifactError,
  ArtifactPreviewProfile,
  ArtifactProbeResultV1,
  ArtifactProbeV1,
} from "@orkestrator/protocol/transcript-artifacts";

import type { ArtifactPrintProfile } from "./print-profile.js";

export interface PreviewRunnerStatus {
  available: boolean;
  /** `container`: OCI worker without network; `process`: owned, killable browser process tree. */
  isolation: "container" | "process" | "unavailable";
  browserBuild: string;
  reason?: string;
  /**
   * Boundary that authored JavaScript (`html-interactive`) would run in.
   * `unavailable` when interactive previews are refused (process mode without
   * the explicit opt-in, or no runner); static HTML and Mermaid may still run.
   */
  interactiveIsolation?: "container" | "process" | "unavailable";
  /** Why interactive previews are refused, when `interactiveIsolation` is `unavailable`. */
  interactiveReason?: string;
  /** How the isolation mode was chosen: `auto` detection or explicit configuration. */
  isolationSelection?: "auto" | "configured";
  /**
   * Worker boundaries whose exit could not be verified. Each still holds its
   * running slot until a bounded reaper confirms it is gone.
   */
  quarantinedWorkers?: number;
  /** Container mode: the image reference jobs run, and whether it is content-addressed. */
  workerImage?: { reference: string; pinned: boolean };
  /**
   * Bundle identity each kind's renderer would report for a job run now.
   * Publication compares a receipt's `rendererBundleHash` with this, so a
   * changed renderer bundle makes older receipts stale. Absent kinds are
   * not compared.
   */
  rendererBundleHashes?: Partial<Record<"html-static" | "html-interactive" | "mermaid", string>>;
}

export interface PreviewJobScope {
  environmentId: string;
  conversationKey: string;
  /** Operation id for fencing and content-free logs. */
  operationId: string;
}

export interface PreviewCapture {
  png: Uint8Array;
  width: number;
  height: number;
  /** `initial` settled document or `final` state after probes. */
  label: "initial" | "final" | "diagnostic";
}

export type PreviewJob =
  | {
      kind: "html-static";
      html: string;
      profile: ArtifactPreviewProfile;
    }
  | {
      kind: "html-interactive";
      /** Exact prepared document bytes (UTF-8 HTML) as stored. */
      preparedDocument: string;
      /** Exact CSP header value generated by the application for this document. */
      contentSecurityPolicy: string;
      profile: ArtifactPreviewProfile;
      probes: ArtifactProbeV1[];
      /** Optional: the prepared package's readiness nonce (`PreparedInteractivePackage.readinessNonce`). */
      readinessNonce?: string;
      /** Optional: lets the worker send the presentation theme message exactly as a viewer would. */
      identity?: { artifactId: string; revision: number };
      /**
       * Optional queue accounting override: authored/package metadata bytes,
       * excluding persisted asset and pinned dependency bodies. Defaults to a
       * bound derived from the document length.
       */
      queuedMetadataBytes?: number;
    }
  | {
      kind: "mermaid";
      source: string;
      theme: "light" | "dark";
    }
  | {
      /**
       * PDF of one verified HTML revision under the fixed print profile.
       * Same admission, deadlines and cancellation as previews; never a receipt.
       */
      kind: "html-print";
      print: ArtifactPrintProfile;
      /** The revision's verified preview profile (theme/viewport for layout). */
      profile: ArtifactPreviewProfile;
      document:
        | { type: "static"; html: string }
        | {
            type: "interactive";
            preparedDocument: string;
            contentSecurityPolicy: string;
            readinessNonce?: string;
            identity?: { artifactId: string; revision: number };
          };
    }
  | {
      /** First page of a PDF attachment (bytes already read through an authorized path). */
      kind: "pdf-thumbnail";
      pdf: Uint8Array;
      maxDimension: number;
    };

export interface PreviewJobSuccessBase {
  browserBuild: string;
  rendererBundleHash: string;
  diagnostics: ArtifactDiagnostic[];
  omittedDiagnostics: number;
  /** Content-free reason codes for blocked network/navigation attempts. */
  blockedRequests: Record<string, number>;
}

export type PreviewJobResult =
  | (PreviewJobSuccessBase & {
      kind: "html-static";
      ok: true;
      /** The sanitized document the runtime actually displayed. */
      effectiveHtml: string;
      captures: PreviewCapture[];
      sanitizer: {
        scripts: number;
        handlers: number;
        externalReferences: number;
        forbiddenElements: number;
        executableUrls: number;
      };
      elementCount: number;
    })
  | (PreviewJobSuccessBase & {
      kind: "html-interactive";
      ok: true;
      captures: PreviewCapture[];
      probeResults: ArtifactProbeResultV1[];
      runtimeErrors: number;
      elementCount: number;
    })
  | (PreviewJobSuccessBase & {
      kind: "mermaid";
      ok: true;
      /** DOMPurify-sanitized SVG, already re-counted against limits. */
      svg: string;
      diagramType: string;
      svgElements: number;
      edges: number;
    })
  | (PreviewJobSuccessBase & {
      kind: "html-print";
      ok: true;
      pdf: Uint8Array;
      pageCount: number;
      /** Static documents: SHA-256 of the sanitized document printed (must match the receipt). */
      effectiveHtmlSha256?: string;
    })
  | (PreviewJobSuccessBase & {
      kind: "pdf-thumbnail";
      ok: true;
      pageCount: number | null;
      /** Page 1, or null when refused with metadata only. */
      thumbnail: PreviewCapture | null;
      refusal?: "page-limit" | "encrypted" | "invalid-pdf";
    })
  | {
      kind: PreviewJob["kind"];
      ok: false;
      error: ArtifactError;
      diagnostics: ArtifactDiagnostic[];
      omittedDiagnostics: number;
      /** Failed-preview evidence; never a receipt. */
      captures: PreviewCapture[];
      probeResults?: ArtifactProbeResultV1[];
      blockedRequests: Record<string, number>;
      browserBuild: string;
    };

export interface PreviewRunner {
  status(): PreviewRunnerStatus;
  /** Re-probe browser availability (bounded; cached). */
  probe(force?: boolean): Promise<PreviewRunnerStatus>;
  /**
   * Admit and run one job. Rejects with an `ArtifactFailure` carrying
   * `capacity_exceeded` (queue full, with the exhausted resource) or
   * `renderer_unavailable` before any work starts. Resolves exactly once with
   * the job's result; the signal requests cancellation of queued or running
   * work, which then resolves `{ ok: false, error: cancelled }`.
   */
  run(job: PreviewJob, scope: PreviewJobScope, signal: AbortSignal): Promise<PreviewJobResult>;
  /**
   * Optional synchronous admission probe: the resource a job for this scope
   * would be refused for right now (`conversation-operations`,
   * `environment-queue`, `global-queue`, …), or null when it would be
   * admitted. Advisory: `run` still decides.
   */
  admissionRefusal?(
    scope: Pick<PreviewJobScope, "environmentId" | "conversationKey">,
  ): string | null;
  close(): Promise<void>;
}

export interface InteractiveAssetInput {
  name: string;
  mimeType: string;
  bytes: Uint8Array;
  sha256: string;
}

export interface PreparedInteractivePackage {
  /** Exact UTF-8 document bytes that will be served and previewed. */
  document: string;
  documentSha256: string;
  byteLength: number;
  /** CSP header generated by application code for exactly this document. */
  contentSecurityPolicy: string;
  scriptHashes: string[];
  dependencyManifestHash: string;
  resolvedDependencies: Array<{ id: string; version: string; sha256: string; license: string }>;
  runtimeVersion: string;
  policyVersion: string;
  readinessNonce: string;
  diagnostics: ArtifactDiagnostic[];
}

export interface InteractivePreparer {
  /** Deterministic for identical inputs; never evaluates authored code. */
  prepare(input: {
    artifactId: string;
    revision: number;
    html: string;
    dependencyIds: string[];
    assets: InteractiveAssetInput[];
  }): Promise<
    | { ok: true; prepared: PreparedInteractivePackage }
    | { ok: false; error: ArtifactError; diagnostics: ArtifactDiagnostic[] }
  >;
  /**
   * Identity of the dependency list `dependencyIds` resolves to under the
   * current manifest (the value a preview records), or of the whole manifest
   * when omitted. An unknown id yields an identity no receipt can match.
   */
  dependencyManifestHash(dependencyIds?: readonly string[]): string;
}

/**
 * Serves prepared executable documents on a dedicated content origin with no
 * application routes or credentials. The service mints a capability only
 * after it has checked ownership.
 */
export interface ArtifactContentServer {
  origin(): string | null;
  /** Optional detail: why live viewing is unavailable (e.g. a same-site content origin). */
  status?(): { available: boolean; origin: string | null; reason?: string };
  mint(input: {
    artifactId: string;
    revision: number;
    preparedSha256: string;
    contentSecurityPolicy: string;
    /** Loads the exact bytes; must verify the hash before serving. */
    load: () => Promise<Uint8Array>;
    /**
     * Re-checks authorization on every request, before `load`: the
     * publication, its owner and environment still exist, and nothing was
     * revoked. Resolving `false` or rejecting fails closed (404) and revokes
     * the capability. Optional: when absent only expiry/revocation apply.
     */
    authorize?: () => Promise<boolean>;
    ttlMs?: number;
  }): {
    url: string;
    /** The browser viewer shell for the same capability (frames exactly `url`). */
    shellUrl: string;
    expiresAt: string;
    generation: string;
  };
  revoke(generation: string): void;
  revokeArtifact(artifactId: string): void;
  close(): Promise<void>;
}
